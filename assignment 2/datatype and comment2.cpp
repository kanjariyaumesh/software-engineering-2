/*Write a C program that includes variables, constants, and comments. Declare 
and use different data types (int, char, float) and display their values. */
#include<stdio.h>
main()
{
	float const pi=3.14;
	int age=22;
	char grade='a';
	float height=5.55;
	
	// constant value
	printf("constant  :%f\n ",pi);
	printf("int      :%d\n",age);
	printf("char      :%c\n",grade);
	printf("float     :%f\n",height);	
}


